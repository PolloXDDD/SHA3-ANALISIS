"""Generate every numerical table and figure directly from recorded results."""
from pathlib import Path
import json
import sys
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = Path(__file__).resolve().parents[1]
DATA, PAPER = ROOT/"results",ROOT/"paper"
FIG = PAPER/"figures"
FIG.mkdir(parents=True,exist_ok=True)


def load(name):
    return json.loads((DATA/(name+".json")).read_text())


def holm(values):
    values = np.asarray(values)
    order = np.argsort(values)
    adjusted = np.empty_like(values)
    top = 0
    for i,j in enumerate(order):
        top = max(top,min(1.0,(len(values)-i)*values[j]))
        adjusted[j] = top
    return adjusted


def table_command(name,columns,header,rows):
    return ("\\newcommand{\\"+name+"}{%\n\\begin{tabular}{"+columns+"}\n\\toprule\n"
            +header+" \\\\\n\\midrule\n"+"\n".join(" & ".join(map(str,row))+" \\\\" for row in rows)
            +"\n\\bottomrule\n\\end{tabular}%\n}\n")


def main():
    diffusion,classifiers,markov = load("diffusion"),load("classifiers"),load("markov")
    causal,cycles = load("causal_graphs"),load("projected_cycles")
    search,ablation = load("search_summary"),load("ablation_summary")
    rounds = [1,2,3,4,6,12,24]
    tables = []
    digest = load("collision_certificate")["reduced_digest_a"]
    tables.append("\\newcommand{\\CollisionDigest}{"+digest[:32]+"\\\\\n"+digest[32:]+"}\n")
    rows = []
    for r in rounds:
        k,c = diffusion[f"kernel_{r}"],diffusion[f"control_{r}"]
        rows.append([r,*[f"{d[part]['mean']:.3f}" for part in ("state","digest") for d in (k,c)]])
    tables.append(table_command("DiffusionTable","rrrrr",r"Rounds & State $K$ & State $C$ & Digest $K$ & Digest $C$",rows))
    rows = [[r,*[f"{classifiers[str(r)][m]['auc']:.4f}" for m in ("hamming","clifford_grades","combined")]] for r in rounds]
    tables.append(table_command("AUCTable","rrrr",r"Rounds & Hamming & Clifford grades & Combined",rows))
    names = [("phase_only","Phase only"),("first_order","First-order bins"),
             ("dyadic_no_feedback","Dyadic, no feedback"),("dyadic_meta","Dyadic, self-feedback")]
    rows = [[label,f"{markov[key]['mean']:.6f}",
             f"[{markov[key]['ci95'][0]:.6f}, {markov[key]['ci95'][1]:.6f}]"] for key,label in names]
    tables.append(table_command("MarkovTable","lrr",r"Predictor & Bits / transition & 95\% interval",rows))
    rows = [[r,f"{causal[str(r)]['mean_influence']:.4f}",f"{causal[str(r)]['mean_abs_ate']:.4f}",
              f"{causal[str(r)]['mean_abs_pearson']:.4f}"] for r in (1,2,3,4,6,12)]
    tables.append(table_command("CausalTable","rrrr",r"Rounds & Mean $I_{ij}$ & Mean $|A_{ij}|$ & Mean $|\rho_{ij}|$",rows))
    rows = [[r,cycles[str(r)]["cycles"],cycles[str(r)]["cyclic_vertices"],cycles[str(r)]["longest_cycle"]] for r in (1,2,12)]
    tables.append(table_command("CyclesTable","rrrr",r"Rounds & Cycles & Cyclic vertices & Longest cycle",rows))
    sr = [2,3,24]
    ps = holm([search[str(r)]["paired_exact_p"] for r in sr])
    rows = [[r,f"{search[str(r)]['random']['successes']}/48",f"{search[str(r)]['meta']['successes']}/48",
             f"{search[str(r)]['paired_exact_p']:.5f}",f"{ps[i]:.5f}"] for i,r in enumerate(sr)]
    tables.append(table_command("SearchTable","rrrrr",r"Rounds & Random & Full model & Exact $p$ & Holm $p$",rows))
    methods = [("random","Random"),("hillclimb","Hill climbing"),("meta_no_feedback","No self-feedback"),
               ("meta_no_scc","Stagnation restart"),("meta","Full model")]
    rows = [[name,f"{ablation['2'][m]['successes']}/48",f"{ablation['2'][m]['mean_queries_censored']:.1f}",
            f"{ablation['24'][m]['successes']}/48",f"{ablation['24'][m]['mean_queries_censored']:.1f}"] for m,name in methods]
    tables.append(table_command("AblationTable","lrrrr",r"Method & $r=2$ hits & Queries & $r=24$ hits & Queries",rows))
    (PAPER/"generated_tables.tex").write_text("% Generated by scripts/build_report.py; do not edit numbers.\n"+"\n".join(tables))

    plt.rcParams.update({"font.family":"DejaVu Sans","font.size":9,"axes.spines.top":False,
        "axes.spines.right":False,"axes.labelsize":9,"axes.titlesize":10,"legend.fontsize":8,
        "pdf.fonttype":42,"figure.dpi":130})
    teal,orange,purple = "#007f86","#cc7136","#6355a4"
    xx = np.arange(len(rounds))
    fig,axes = plt.subplots(1,2,figsize=(7.1,2.9),layout="constrained")
    for name,label,color in (("kernel","Parity-kernel difference",teal),("control","Two-bit control",orange)):
        vals = [diffusion[f"{name}_{r}"]["state"]["mean"]/1600 for r in rounds]
        axes[0].plot(xx,vals,"o-",color=color,ms=4,label=label)
    axes[0].axhline(.5,ls="--",lw=.8,color="gray")
    axes[0].set(xlabel="Prefix rounds",ylabel="Mean changed fraction of 1600 bits",xticks=xx,xticklabels=rounds,ylim=(-.01,.56))
    axes[0].legend(loc="lower right",frameon=False)
    for name,label,color,offset in (("hamming","Hamming",orange,-.12),("clifford_grades","Clifford grades",purple,0),
                                   ("combined","Combined",teal,.12)):
        vals = np.array([classifiers[str(r)][name]["auc"] for r in rounds])
        ci = np.array([classifiers[str(r)][name]["ci95"] for r in rounds])
        axes[1].errorbar(xx+offset,vals,yerr=np.maximum(0,np.array([vals-ci[:,0],ci[:,1]-vals])),
                         fmt="o",ms=3,capsize=2,color=color,label=label)
    axes[1].axhline(.5,ls="--",lw=.8,color="gray")
    axes[1].set(xlabel="Prefix rounds",ylabel="Held-out ROC AUC",xticks=xx,xticklabels=rounds,ylim=(.40,1.04))
    axes[1].legend(loc="center right",frameon=False)
    fig.savefig(FIG/"diffusion_and_auc.pdf")
    plt.close(fig)

    data = np.load(DATA/"causal_matrices.npz")
    fig,axes = plt.subplots(2,2,figsize=(6.7,5.2),layout="constrained")
    for j,r in enumerate((1,12)):
        im = axes[0,j].imshow(data[f"influence_{r}"],vmin=0,vmax=1,cmap="viridis",origin="lower")
        axes[0,j].set_title(f"Paired influence, {r} round"+("s" if r>1 else ""))
        axes[0,j].set(xlabel="Output bit",ylabel="Intervened input bit")
        im2 = axes[1,j].imshow(data[f"correlation_{r}"],vmin=-1,vmax=1,cmap="RdBu_r",origin="lower")
        axes[1,j].set_title(f"Pearson correlation, {r} round"+("s" if r>1 else ""))
        axes[1,j].set(xlabel="Output bit",ylabel="Observed input bit")
    for ax in axes.ravel():
        ax.set_xticks([0,6,12,18,24]); ax.set_yticks([0,6,12,18,24])
    fig.colorbar(im,ax=axes[0,:],shrink=.85)
    fig.colorbar(im2,ax=axes[1,:],shrink=.85)
    fig.savefig(FIG/"causal_influence.pdf")
    plt.close(fig)

    fig,ax = plt.subplots(figsize=(6.7,2.9),layout="constrained")
    for method,label,color,offset in (("random","Random",orange,-.18),("meta","Full model",teal,.18)):
        vals = np.array([search[str(r)][method]["success_rate"] for r in sr])
        ci = np.array([search[str(r)][method]["wilson_ci95"] for r in sr])
        ax.bar(np.arange(3)+offset,vals,.33,color=color,label=label)
        ax.errorbar(np.arange(3)+offset,vals,yerr=[vals-ci[:,0],ci[:,1]-vals],fmt="none",color="#303030",capsize=3,lw=1)
    ax.axhline(search["settings"]["ideal_random_success_probability"],ls="--",color="#666666",lw=1,label="Ideal independent outputs")
    ax.set(xticks=range(3),xticklabels=["2 rounds","3 rounds","24 rounds"],ylabel="12-bit target success rate",ylim=(0,1.02))
    ax.legend(frameon=False,loc="upper right")
    fig.savefig(FIG/"truncated_search.pdf")
    plt.close(fig)

    fig,axes = plt.subplots(1,2,figsize=(7.1,3.2),layout="constrained")
    for ax,r in zip(axes,(2,24)):
        vals = np.array([ablation[str(r)][m]["successes"]/48 for m,_ in methods])
        ci = np.array([ablation[str(r)][m]["wilson_ci95"] for m,_ in methods])
        ax.bar(range(5),vals,color=[orange,"#8e9aa7",purple,"#78b9b4",teal])
        ax.errorbar(range(5),vals,yerr=[vals-ci[:,0],ci[:,1]-vals],fmt="none",color="#333333",capsize=2,lw=.8)
        ax.set(xticks=range(5),xticklabels=["Random","Hill climb","No feedback","No SCC","Full model"],
               ylabel="12-bit target success rate",ylim=(0,1.04),title=f"Independent replication: {r} rounds")
        ax.tick_params(axis="x",labelrotation=30,labelsize=8)
        ax.axhline(search["settings"]["ideal_random_success_probability"],ls="--",color="gray",lw=.8)
    fig.savefig(FIG/"search_ablations.pdf")
    plt.close(fig)
    print("Generated seven tables and four vector figures.")


if __name__ == "__main__":
    main()
